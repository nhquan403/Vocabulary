#!/usr/bin/env node
// Build js/data.js from data/src and verify that every word in every story
// resolves to a dictionary entry. Exits with code 1 on any problem.
'use strict';
const fs = require('fs');
const path = require('path');
const { lemma, TOKEN_RE } = require('../js/lemma.js');

const ROOT = path.join(__dirname, '..');
const SRC = path.join(ROOT, 'data', 'src');
const MIN_WORDS = 3000;

function readTsv(file) {
  return fs.readFileSync(file, 'utf8').split(/\r?\n/)
    .map((l) => l.trim()).filter((l) => l && !l.startsWith('#'))
    .map((l) => l.split('|').map((x) => x.trim()));
}

const problems = [];
const dict = {};
const wordFiles = fs.readdirSync(SRC).filter((f) => /^words-.*\.txt$/.test(f)).sort();
for (const f of wordFiles) {
  readTsv(path.join(SRC, f)).forEach((cols, i) => {
    const [word, pos, meaning] = cols;
    if (!word || !pos || !meaning) { problems.push(`${f}:${i + 1} malformed line: ${cols.join(' | ')}`); return; }
    const key = word.toLowerCase();
    if (dict[key]) return; // first definition wins
    dict[key] = { w: word, p: pos, m: meaning };
  });
}

const irr = {};
const irrFile = path.join(SRC, 'irregular.txt');
if (fs.existsSync(irrFile)) {
  for (const [form, base] of readTsv(irrFile)) {
    irr[form.toLowerCase()] = base.toLowerCase();
    if (!dict[base.toLowerCase()]) problems.push(`irregular.txt: base "${base}" (for "${form}") is not in the dictionary`);
  }
}

const storyDir = path.join(SRC, 'stories');
const stories = [];
const missing = {};
const usage = {};
for (const f of fs.readdirSync(storyDir).filter((x) => x.endsWith('.txt')).sort()) {
  const raw = fs.readFileSync(path.join(storyDir, f), 'utf8').replace(/\r/g, '');
  const [titleLine, ...rest] = raw.split('\n');
  const title = titleLine.trim();
  const paragraphs = rest.join('\n').split(/\n\s*\n/).map((p) => p.replace(/\s+/g, ' ').trim()).filter(Boolean);
  let count = 0;
  for (const text of [title, ...paragraphs]) {
    for (const tok of text.match(TOKEN_RE) || []) {
      if (text !== title) count++;
      const l = lemma(tok, dict, irr);
      if (!l) (missing[tok.toLowerCase()] = missing[tok.toLowerCase()] || new Set()).add(f);
      else usage[l] = (usage[l] || 0) + 1;
    }
  }
  const id = f.replace(/\.txt$/, '');
  const audioPath = `audio/stories/${id}.mp3`;
  const story = { id, title, words: count, paragraphs };
  if (fs.existsSync(path.join(ROOT, audioPath))) story.audio = audioPath;
  stories.push(story);
}

const names = Object.values(dict).filter((e) => e.p === 'name').length;
const realWords = Object.keys(dict).length - names;
if (realWords < MIN_WORDS) problems.push(`dictionary has ${realWords} words (names excluded), need >= ${MIN_WORDS}`);
const missingList = Object.keys(missing).sort();
if (missingList.length) problems.push(`${missingList.length} story words not in dictionary:\n  ` +
  missingList.map((w) => `${w} (${[...missing[w]].join(', ')})`).join('\n  '));

const out = '// Generated by scripts/build.js — do not edit by hand.\n' +
  'window.DICT = ' + JSON.stringify(dict) + ';\n' +
  'window.IRREG = ' + JSON.stringify(irr) + ';\n' +
  'window.STORIES = ' + JSON.stringify(stories) + ';\n';
fs.writeFileSync(path.join(ROOT, 'js', 'data.js'), out);

const used = Object.keys(usage).length;
console.log(`dictionary: ${realWords} words + ${names} names`);
console.log(`stories: ${stories.length}`);
stories.forEach((s) => console.log(`  ${s.id}: ${s.words} words`));
console.log(`distinct dictionary entries used in stories: ${used}`);
if (problems.length) {
  console.error('\nPROBLEMS:\n' + problems.join('\n'));
  process.exit(1);
}
console.log('OK');
