#!/usr/bin/env python3
"""Find when each word of a story is spoken in its narration MP3 (free, offline; needs ffmpeg).

Usage:
  pip install faster-whisper
  python scripts/align-story-audio.py [--voice us|in|in-strong] [--model base.en] [story ids...]

With no story ids, every story that has an MP3 for that voice is aligned. For each
<root>/stories/<id>.mp3 it writes <root>/stories/<id>.timings.js holding the start time
(in hundredths of a second) of every word token, in the same order as the reading page
numbers them (title first, then paragraphs; same token rule as TOKEN_RE in js/lemma.js).
"""
import argparse
import difflib
import json
import os
import re
import subprocess

import numpy as np

from faster_whisper import WhisperModel

from voices import VOICES

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
TOKEN_RE = re.compile(r"[A-Za-z]+(?:['’][A-Za-z]+)?")


def norm(word):
    return word.lower().replace("’", "'")


def story_tokens(story_id):
    path = os.path.join(ROOT, "data", "src", "stories", story_id + ".txt")
    with open(path, encoding="utf-8") as f:
        title, _, rest = f.read().replace("\r", "").partition("\n")
    paragraphs = [" ".join(p.split()) for p in rest.split("\n\n") if p.strip()]
    tokens = []
    for text in [title.strip()] + paragraphs:
        tokens += [norm(t) for t in TOKEN_RE.findall(text)]
    return tokens


def spoken_words(model, mp3):
    # Decode with ffmpeg (16 kHz mono float) instead of the PyAV reader.
    pcm = subprocess.run(["ffmpeg", "-loglevel", "error", "-i", mp3, "-f", "f32le", "-ac", "1", "-ar", "16000", "-"],
                         check=True, capture_output=True).stdout
    segments, _ = model.transcribe(np.frombuffer(pcm, dtype=np.float32), language="en", word_timestamps=True, beam_size=5,
                                   condition_on_previous_text=False)
    words = []
    for seg in segments:
        for w in seg.words:
            for t in TOKEN_RE.findall(w.word):
                words.append((norm(t), w.start))
    return words


def align(tokens, words):
    """Start time per story token: matched words exactly, the rest interpolated."""
    times = [None] * len(tokens)
    sm = difflib.SequenceMatcher(None, tokens, [w for w, _ in words], autojunk=False)
    for a, b, size in sm.get_matching_blocks():
        for k in range(size):
            times[a + k] = words[b + k][1]
    matched = sum(t is not None for t in times)
    known = [i for i, t in enumerate(times) if t is not None]
    for i in range(len(times)):
        if times[i] is not None:
            continue
        before = max((k for k in known if k < i), default=None)
        after = min((k for k in known if k > i), default=None)
        if before is None:
            times[i] = times[after] if after is not None else 0.0
        elif after is None:
            times[i] = times[before]
        else:
            frac = (i - before) / (after - before)
            times[i] = times[before] + frac * (times[after] - times[before])
    return times, matched


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--voice", choices=sorted(VOICES), default="us")
    ap.add_argument("--model", default="base.en", help="faster-whisper model name")
    ap.add_argument("stories", nargs="*")
    args = ap.parse_args()

    root = VOICES[args.voice]["root"]
    folder = os.path.join(ROOT, root, "stories")
    ids = args.stories or sorted(f[:-4] for f in os.listdir(folder) if f.endswith(".mp3"))
    model = WhisperModel(args.model, device="cpu", compute_type="int8")

    for story_id in ids:
        mp3 = os.path.join(folder, story_id + ".mp3")
        tokens = story_tokens(story_id)
        times, matched = align(tokens, spoken_words(model, mp3))
        key = f"{root}/stories/{story_id}"
        data = json.dumps([round(t * 100) for t in times], separators=(",", ":"))
        with open(os.path.join(folder, story_id + ".timings.js"), "w", encoding="utf-8") as f:
            f.write("// Generated by scripts/align-story-audio.py: start of each word in 1/100 s.\n")
            f.write(f'(window.STORY_TIMINGS = window.STORY_TIMINGS || {{}})["{key}"] = {data};\n')
        print(f"{key}: {matched}/{len(tokens)} words matched ({matched * 100 // len(tokens)}%)", flush=True)


if __name__ == "__main__":
    main()
